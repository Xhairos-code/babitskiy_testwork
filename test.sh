#!/bin/bash
a=33 #Присваиваем число
let "a+=1" #Прибавляем к нашему числу 1
b=SA34 #Присваиваем переменной b текст и число
let "b+=1" #Интерпритаттор не может понять почему и числа и буквы в переменной b 
           #и задает ей значение 0, к которому мы прибавили 1 тут мы получим 1
b=SA34 #Возвращаем переменной значение текст и число
a=${b/SA/33} #Переменной a присваиваем значение b(SA34) которое заменяет буквы SA на цифры 33 получаем 3334
